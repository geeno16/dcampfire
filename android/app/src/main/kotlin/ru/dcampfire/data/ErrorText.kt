package ru.dcampfire.data

import ru.dcampfire.client.ApiProblem

fun errorText(p: ApiProblem): String = when (p.code) {
    "UNAUTHORIZED" -> "Сессия закончилась. Войдите снова."

    "INVALID_CREDENTIALS" -> "Неверная почта или пароль."

    "EMAIL_NOT_VERIFIED" -> "Сначала подтвердите почту."

    "EMAIL_TAKEN" -> "Этот адрес почты уже зарегистрирован."

    "NICKNAME_TAKEN" -> "Этот псевдоним уже занят."

    "CODE_INVALID" -> if (p.attemptsLeft == 0) {
        "Попытки закончились. Запросите новый код."
    } else {
        "Неверный код." + (p.attemptsLeft?.let { " Осталось попыток: $it." } ?: "")
    }

    "CODE_EXPIRED" -> "Код устарел. Запросите новый."

    "CODE_ATTEMPTS_EXCEEDED" -> "Попытки закончились. Запросите новый код."

    "RESEND_TOO_EARLY" -> "Новый код можно запросить через ${p.retryAfter ?: 60} с."

    "PAUSE_ACTIVE" -> "Следующее сообщение можно отправить через ${p.retryAfter ?: 10} с."

    "WRONG_PASSWORD" -> "Неверный текущий пароль."

    "BONFIRE_FULL" -> "В костре нет свободных мест."

    "BONFIRE_LIMIT_REACHED" -> "Достигнут лимит костров. Сначала покиньте один из них."

    "BONFIRE_NOT_FOUND" -> "Костёр удалён или больше вам недоступен."

    "FORBIDDEN" -> "Это действие доступно только хозяину костра."

    "USER_NOT_FOUND" -> "Пользователь с таким псевдонимом не найден."

    "MEMBER_NOT_FOUND" -> "Этот участник уже покинул костёр."

    "INVITATION_NOT_FOUND" -> "Приглашение уже недоступно."

    "ALREADY_MEMBER" -> "Пользователь уже в этом костре."

    "ALREADY_INVITED" -> "Приглашение уже отправлено."

    "OWNER_CANNOT_LEAVE" -> "Хозяин может удалить костёр в его настройках."

    "ALBUM_NOT_FOUND" -> "Альбом не найден. Проверьте ссылку."

    "ALBUM_LOOKUP_FAILED" -> "Яндекс Музыка сейчас недоступна. Попробуйте позже."

    "EMAIL_SEND_FAILED" -> "Не удалось отправить письмо. Попробуйте позже."

    "TOPIC_NOT_FOUND" -> "Список тем изменился. Обновите экран."

    "VALIDATION_FAILED" -> "Проверьте заполненные поля."

    else -> "Не удалось выполнить действие. Попробуйте ещё раз."
}
fun fieldText(field: String): String = when (field.substringBefore('.')) {
    "nickname" -> "Псевдоним должен содержать от 3 до 20 символов."
    "email" -> "Введите корректный адрес почты."
    "password", "new_password" -> "Пароль должен содержать от 8 до 128 символов."
    "code" -> "Введите 6 цифр из письма."
    "name" -> "Название должно содержать от 3 до 40 символов."
    "album_url", "url" -> "Нужна ссылка на альбом Яндекс Музыки."
    "file" -> "Выберите целое изображение JPEG или PNG до 5 МБ и 20 мегапикселей."
    "body" -> "Введите сообщение до 1000 символов."
    "topic_ids" -> "Проверьте количество выбранных тем."
    else -> "Проверьте значение этого поля."
}
